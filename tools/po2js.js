#!/usr/bin/env node
// Converts src/locales/*.po into a JavaScript file that defines PO_TRANSLATIONS,
// a { locale: { msgid: msgstr } } table that build.sh prepends to index.js.
// It also checks every .po against messages.pot and exits non-zero on problems:
// missing or unknown msgids, and {placeholders} that differ from the msgid.
//
// Usage: node tools/po2js.js <locales dir> [<output .js file>]
// Without an output file it only runs the checks.

'use strict';
const fs = require('fs');
const path = require('path');

function unquote(line, file, lineNo) {
	const m = /^"((?:[^"\\]|\\.)*)"$/.exec(line);
	if (!m) throw new Error(`${file}:${lineNo}: expected a quoted string`);
	return m[1].replace(/\\(.)/g, (_, c) => ({ n: '\n', t: '\t', r: '\r', '"': '"', '\\': '\\' }[c] ?? c));
}

// Returns [{ msgid, msgstr, fuzzy }] for every entry except the header.
function parsePo(file) {
	const entries = [];
	let entry = null;
	let field = null;
	let fuzzy = false;
	const flush = () => {
		if (entry && entry.msgid !== '') entries.push(entry);
		entry = null;
		field = null;
	};
	fs.readFileSync(file, 'utf8').split(/\r?\n/).forEach((raw, i) => {
		const line = raw.trim();
		if (!line) { flush(); fuzzy = false; return; }
		if (line.startsWith('#,')) { fuzzy = /\bfuzzy\b/.test(line); return; }
		if (line.startsWith('#')) return;
		const m = /^(msgid|msgstr)\s+(".*")$/.exec(line);
		if (m) {
			if (m[1] === 'msgid') { flush(); entry = { msgid: '', msgstr: '', fuzzy }; fuzzy = false; }
			else if (!entry) throw new Error(`${file}:${i + 1}: msgstr without msgid`);
			field = m[1];
			entry[field] = unquote(m[2], file, i + 1);
		} else if (line.startsWith('"') && entry && field) {
			entry[field] += unquote(line, file, i + 1);
		} else {
			throw new Error(`${file}:${i + 1}: unsupported line: ${line}`);
		}
	});
	flush();
	return entries;
}

const placeholders = s => (s.match(/\{[a-z]+\}/g) || []).sort().join(' ');

function main() {
	const [dir, output] = process.argv.slice(2);
	if (!dir) { console.error('Usage: node tools/po2js.js <locales dir> [<output .js file>]'); process.exit(2); }

	const ids = new Set(parsePo(path.join(dir, 'messages.pot')).map(e => e.msgid));
	const table = {};
	const problems = [];

	for (const name of fs.readdirSync(dir).filter(f => f.endsWith('.po')).sort()) {
		const locale = path.basename(name, '.po');
		const messages = {};
		const seen = new Set();
		for (const { msgid, msgstr, fuzzy } of parsePo(path.join(dir, name))) {
			seen.add(msgid);
			if (!ids.has(msgid)) { problems.push(`${name}: msgid not in messages.pot: ${JSON.stringify(msgid)}`); continue; }
			if (!msgstr || fuzzy) continue; // untranslated: falls back to English
			if (placeholders(msgid) !== placeholders(msgstr)) {
				problems.push(`${name}: placeholders differ for ${JSON.stringify(msgid)}`);
				continue;
			}
			messages[msgid] = msgstr;
		}
		for (const id of ids) if (!seen.has(id)) problems.push(`${name}: missing msgid ${JSON.stringify(id)}`);
		table[locale] = messages;
	}

	if (problems.length) {
		console.error(problems.join('\n'));
		process.exit(1);
	}

	if (output) {
		const js = '// Generated by tools/po2js.js from src/locales/*.po. Do not edit.\n'
			+ 'const PO_TRANSLATIONS = ' + JSON.stringify(table, null, '\t') + ';\n\n';
		fs.writeFileSync(output, js);
	}
	const counts = Object.entries(table).map(([l, m]) => `${l} ${Object.keys(m).length}/${ids.size}`);
	console.error('Translations: ' + counts.join(', '));
}

main();
